"""Independent exported-netlist and real-footprint checks; mutation-tested."""
from pathlib import Path
import json, sys, xml.etree.ElementTree as ET, unittest, copy
HERE=Path(__file__).resolve().parent

def load_net(paths):
    nodes={};values={};footprints={}
    for path in paths:
        root=ET.parse(path).getroot()
        for c in root.findall('./components/comp'):
            ref=c.attrib['ref']; assert ref not in values, ref
            values[ref]=c.findtext('value');footprints[ref]=c.findtext('footprint')
        for net in root.findall('./nets/net'):
            for node in net.findall('node'):
                nodes[node.attrib['ref'],node.attrib['pin']]=net.attrib['name']
    return nodes,values,footprints

