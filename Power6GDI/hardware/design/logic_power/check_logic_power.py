class ElectricalTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls): cls.data=load_net([HERE/'work/logic_5v.xml',HERE/'work/logic_3v3.xml'])
    def test_exported_pinmap(self):validate(*self.data)
    def test_reversed_input_diode_rejected(self):
        d=copy.deepcopy(self.data);d[0]['D5200','2']='VBAT_MAIN_FUSED'
        with self.assertRaises(AssertionError):validate(*d)
    def test_boot_cap_ground_error_rejected(self):
        d=copy.deepcopy(self.data);d[0]['C5203','2']='GND'
        with self.assertRaises(AssertionError):validate(*d)
    def test_circular_sequence_rejected(self):
        d=copy.deepcopy(self.data);d[0]['R5204','1']='+3V3'
        with self.assertRaises(AssertionError):validate(*d)
    def test_wrong_TPS_frequency_rejected(self):
        d=copy.deepcopy(self.data);d[0]['U5300','7']='GND'
        with self.assertRaises(AssertionError):validate(*d)
    def test_parallel_old_LDO_rejected(self):
        d=copy.deepcopy(self.data);d[1]['U102']='TLV1117LV33DCYR'
        with self.assertRaises(AssertionError):validate(*d,integrated=True)
    def test_current_and_voltage_envelopes(self):
        from calculate import calculate
        b=calculate(); self.assertLess(b['rail5v_combined_A'],2);self.assertLess(b['rail3v3_allocated_A'],1)
        self.assertLess(b['peak_5v_A_at2A'],4.35); self.assertLess(b['peak_3v3_A_at1A'],3.6)
        lo,hi=b['feedback_static_bounds_V']['3V3_PSM'];self.assertGreater(lo,3.135);self.assertLess(hi,3.465)
    def test_all_physical_pins(self):
        # Report generated by pcbnew against actual installed library geometry.
        report=json.loads((HERE/'footprint_check.json').read_text())
        self.assertEqual(report['count'],32);self.assertEqual(report['errors'],[])
